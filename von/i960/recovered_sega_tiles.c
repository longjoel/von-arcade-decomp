void recovered_sega_logo_tiles(void)
{
    u32 index;
    /* The original bumper starts from a clean pair of 64x64 tile layers.
     * Clear the active maps so the reconstructed text bootstrap cannot bleed
     * into the captured logo placement. */
    for (index = 0U; index < 0x1000U; ++index)
        TILE_RAM[index] = 0U;
    for (index = 0U; index < (u32)(sizeof(WRITES) / sizeof(WRITES[0])); ++index)
        TILE_RAM[WRITES[index].offset] = WRITES[index].value;
}
